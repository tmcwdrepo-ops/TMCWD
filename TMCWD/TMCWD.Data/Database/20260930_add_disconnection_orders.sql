CREATE TABLE IF NOT EXISTS `disconnection_orders` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `account_id` BIGINT NOT NULL,
  `job_order_number` VARCHAR(50) NOT NULL,
  `job_order_date` DATETIME NOT NULL,
  `disconnection_date` DATETIME NULL,
  `nature_of_disconnection` VARCHAR(100) NOT NULL DEFAULT '',
  `possession` VARCHAR(100) NOT NULL DEFAULT '',
  `reason` VARCHAR(255) NOT NULL DEFAULT '',
  `last_reading` DECIMAL(12,2) NULL,
  `plumber` VARCHAR(150) NOT NULL DEFAULT '',
  `reconnection_fee` DECIMAL(12,2) NOT NULL DEFAULT 350.00,
  `remarks` TEXT NULL,
  `charge_fee` TINYINT(1) NOT NULL DEFAULT 1,
  `reading_override` TINYINT(1) NOT NULL DEFAULT 0,
  `status` VARCHAR(30) NOT NULL DEFAULT 'Disconnected',
  `processed_by` BIGINT NOT NULL,
  `created_at` DATETIME NOT NULL,
  `updated_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_disconnection_orders_job_order_number` (`job_order_number`),
  KEY `ix_disconnection_orders_account_id` (`account_id`),
  KEY `ix_disconnection_orders_status` (`status`),
  CONSTRAINT `fk_disconnection_orders_account` FOREIGN KEY (`account_id`) REFERENCES `accounts` (`Id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
