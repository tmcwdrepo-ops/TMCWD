CREATE TABLE IF NOT EXISTS `service_request_orders` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `is_non_customer` TINYINT(1) NOT NULL DEFAULT 0,
  `account_id` BIGINT NULL,
  `account_number` VARCHAR(50) NOT NULL DEFAULT '',
  `account_name` VARCHAR(200) NOT NULL DEFAULT '',
  `address` VARCHAR(500) NOT NULL,
  `reported_by` VARCHAR(200) NOT NULL,
  `contact_number` VARCHAR(30) NOT NULL,
  `job_order_number` VARCHAR(50) NOT NULL,
  `job_order_date` DATETIME NOT NULL,
  `source` VARCHAR(50) NOT NULL,
  `job_order_type` VARCHAR(100) NOT NULL,
  `job_description` VARCHAR(255) NOT NULL,
  `referred_to_user_id` BIGINT NULL,
  `date_referred` DATETIME NULL,
  `name` VARCHAR(200) NOT NULL DEFAULT '',
  `particulars` TEXT NULL,
  `received_by_user_id` BIGINT NOT NULL,
  `status` VARCHAR(30) NOT NULL DEFAULT 'Open',
  `created_at` DATETIME NOT NULL,
  `updated_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `ux_service_request_job_order_number` (`job_order_number`),
  KEY `ix_service_request_account_id` (`account_id`),
  KEY `ix_service_request_referred_to` (`referred_to_user_id`),
  KEY `ix_service_request_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
